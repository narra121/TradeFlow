/**
 * Builds the CloudFront Function (runtime cloudfront-js-2.0) that serves prerendered pages.
 * Output is committed at infra/cloudfront/router.js; src/content/__tests__/cf-router.test.ts fails
 * when it is stale. Regenerate: `bun scripts/seo/cf-router.ts --write`.
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { CANONICAL_HOST, REDIRECT_HOSTS, SPA_PREFIXES } from '../../src/content/route-registry';

/** Repo-root relative: package scripts and vitest both run from the repo root. */
export const ROUTER_PATH = resolve(process.cwd(), 'infra', 'cloudfront', 'router.js');
const INDEX_HTML_PATH = resolve(process.cwd(), 'index.html');

/**
 * `'sha256-...'` sources for every inline `<script>` in index.html (the boot script that reads the stored session). A browser hashes
 * the script text after its HTML parser has turned CRLF into LF, so the hash is taken the same way and a Windows checkout matches CI.
 * Edit that script and this file's output changes, which cf-router.test.ts reports until the router is regenerated.
 */
export function inlineScriptHashes(): string[] {
  const html = readFileSync(INDEX_HTML_PATH, 'utf8');
  const hashes = [...html.matchAll(/<script>([\s\S]*?)<\/script>/g)].map(
    ([, text]) => `'sha256-${createHash('sha256').update(text.replace(/\r\n?/g, '\n')).digest('base64')}'`,
  );
  if (!hashes.length) throw new Error('index.html has no inline <script>: the CSP hash list would be empty');
  return hashes;
}

const GOOGLE_ANALYTICS = ['https://*.google-analytics.com', 'https://*.googletagmanager.com'];
// Off at launch (VITE_ADS_ENABLED); listed so switching ads on does not start with a wall of violations.
const GOOGLE_ADS = ['https://pagead2.googlesyndication.com', 'https://*.g.doubleclick.net'];

/**
 * What the site loads, per directive. Static analysis of src/, index.html and the prerendered pages: gtag.js and its beacons (GA4),
 * the AdSense loader, Cognito (Amplify Auth calls cognito-idp and the hosted-UI domain), the API (a custom domain under tradequt.com,
 * or an execute-api URL on dev), presigned S3 PUTs for screenshots, and blob: URLs for screenshots read through the API.
 * Styles stay 'unsafe-inline' (React style props, index.html and the static error pages carry inline CSS).
 * Fonts allow data: because a prerendered page carries its text font inline (scripts/prerender-routes.js).
 */
function contentSecurityPolicy(): string {
  return [
    "default-src 'self'",
    `script-src 'self' ${inlineScriptHashes().join(' ')} https://www.googletagmanager.com https://pagead2.googlesyndication.com`,
    "style-src 'self' 'unsafe-inline'",
    `img-src 'self' data: blob: ${[...GOOGLE_ANALYTICS, ...GOOGLE_ADS].join(' ')}`,
    "font-src 'self' data:",
    `connect-src 'self' https://*.tradequt.com https://*.execute-api.us-east-1.amazonaws.com https://cognito-idp.us-east-1.amazonaws.com https://*.s3.us-east-1.amazonaws.com ${[
      ...GOOGLE_ANALYTICS,
      'https://analytics.google.com',
      'https://*.analytics.google.com',
      ...GOOGLE_ADS,
    ].join(' ')}`,
    'frame-src https://googleads.g.doubleclick.net https://tpc.googlesyndication.com',
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
  ].join('; ');
}

/** On every response. */
const SECURITY_HEADERS: Record<string, string> = {
  'strict-transport-security': 'max-age=31536000',
  'x-content-type-options': 'nosniff',
  'referrer-policy': 'strict-origin-when-cross-origin',
};

/**
 * On HTML responses only. The full policy is Report-Only until a live check shows no violation for a source that was missed; the
 * enforced one carries only frame-ancestors, which no page here needs to be loosened for.
 */
function pageHeaders(): Record<string, string> {
  return {
    'content-security-policy': "frame-ancestors 'none'",
    'content-security-policy-report-only': contentSecurityPolicy(),
  };
}

export function buildRouterSource(): string {
  return `// GENERATED by scripts/seo/cf-router.ts from src/content/route-registry.ts - do not edit by hand.
// Associate with BOTH viewer-request and viewer-response of the default cache behavior.
var CANONICAL_HOST = ${JSON.stringify(CANONICAL_HOST)};
var REDIRECT_HOSTS = ${JSON.stringify(REDIRECT_HOSTS)};
var SPA_PREFIXES = ${JSON.stringify(SPA_PREFIXES)};
var SPA_SHELL = '/_spa.html';
var SECURITY_HEADERS = ${JSON.stringify(SECURITY_HEADERS)};
var PAGE_HEADERS = ${JSON.stringify(pageHeaders())};

function queryString(q) {
  var parts = [];
  for (var key in q) {
    var entry = q[key];
    var values = entry.multiValue ? entry.multiValue : [entry];
    for (var i = 0; i < values.length; i++) {
      parts.push(values[i].value === '' ? key : key + '=' + values[i].value);
    }
  }
  return parts.length ? '?' + parts.join('&') : '';
}

function redirect(location) {
  return {
    statusCode: 301,
    statusDescription: 'Moved Permanently',
    headers: { location: { value: location }, 'cache-control': { value: 'max-age=3600' } }
  };
}

function isSpa(uri) {
  for (var i = 0; i < SPA_PREFIXES.length; i++) {
    var p = SPA_PREFIXES[i];
    if (uri === p || uri.indexOf(p + '/') === 0) return true;
  }
  return false;
}

function handler(event) {
  var request = event.request;
  var host = request.headers.host ? request.headers.host.value.toLowerCase() : '';

  if (event.context.eventType === 'viewer-response') {
    var response = event.response;
    for (var name in SECURITY_HEADERS) response.headers[name] = { value: SECURITY_HEADERS[name] };
    var type = response.headers['content-type'];
    if (type && type.value.indexOf('text/html') === 0) {
      for (var page in PAGE_HEADERS) response.headers[page] = { value: PAGE_HEADERS[page] };
    }
    if (host !== CANONICAL_HOST) response.headers['x-robots-tag'] = { value: 'noindex, nofollow' };
    return response;
  }

  var uri = request.uri;
  if (REDIRECT_HOSTS.indexOf(host) !== -1) {
    return redirect('https://' + CANONICAL_HOST + uri + queryString(request.querystring));
  }
  if (uri === '/') {
    request.uri = '/index.html';
    return request;
  }
  if (isSpa(uri)) {
    request.uri = SPA_SHELL;
    return request;
  }
  if (uri === '/index.html') return redirect('/' + queryString(request.querystring));
  if (uri.length > 11 && uri.slice(-11) === '/index.html') {
    return redirect(uri.slice(0, -11) + queryString(request.querystring));
  }
  if (uri.charAt(uri.length - 1) === '/') {
    return redirect((uri.replace(/\\/+$/, '') || '/') + queryString(request.querystring));
  }
  var last = uri.substring(uri.lastIndexOf('/') + 1);
  if (last.indexOf('.') === -1) request.uri = uri + '/index.html';
  return request;
}
`;
}

if (process.argv.includes('--write')) {
  writeFileSync(ROUTER_PATH, buildRouterSource(), 'utf8');
  console.log(`wrote ${ROUTER_PATH}`);
}
