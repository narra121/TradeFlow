/**
 * Builds the CloudFront Function (runtime cloudfront-js-2.0) that serves prerendered pages.
 * Output is committed at infra/cloudfront/router.js; src/content/__tests__/cf-router.test.ts fails
 * when it is stale. Regenerate: `bun scripts/seo/cf-router.ts --write`.
 */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { CANONICAL_HOST, REDIRECT_HOSTS, SPA_PREFIXES } from '../../src/content/route-registry';

/** Repo-root relative: package scripts and vitest both run from the repo root. */
export const ROUTER_PATH = resolve(process.cwd(), 'infra', 'cloudfront', 'router.js');

export function buildRouterSource(): string {
  return `// GENERATED by scripts/seo/cf-router.ts from src/content/route-registry.ts - do not edit by hand.
// Associate with BOTH viewer-request and viewer-response of the default cache behavior.
var CANONICAL_HOST = ${JSON.stringify(CANONICAL_HOST)};
var REDIRECT_HOSTS = ${JSON.stringify(REDIRECT_HOSTS)};
var SPA_PREFIXES = ${JSON.stringify(SPA_PREFIXES)};
var SPA_SHELL = '/_spa.html';

function queryString(q) {
  var parts = [];
  for (var key in q) {
    var entry = q[key];
    var values = entry.multiValue ? entry.multiValue : [entry];
    for (var i = 0; i < values.length; i++) {
      parts.push(values[i].value === '' ? key : key + '=' + values[i].value);
    }
  }
  return parts.length ? '?' + parts.join('&') : '';
}

function redirect(location) {
  return {
    statusCode: 301,
    statusDescription: 'Moved Permanently',
    headers: { location: { value: location }, 'cache-control': { value: 'max-age=3600' } }
  };
}

function isSpa(uri) {
  for (var i = 0; i < SPA_PREFIXES.length; i++) {
    var p = SPA_PREFIXES[i];
    if (uri === p || uri.indexOf(p + '/') === 0) return true;
  }
  return false;
}

function handler(event) {
  var request = event.request;
  var host = request.headers.host ? request.headers.host.value.toLowerCase() : '';

  if (event.context.eventType === 'viewer-response') {
    var response = event.response;
    if (host !== CANONICAL_HOST) response.headers['x-robots-tag'] = { value: 'noindex, nofollow' };
    return response;
  }

  var uri = request.uri;
  if (REDIRECT_HOSTS.indexOf(host) !== -1) {
    return redirect('https://' + CANONICAL_HOST + uri + queryString(request.querystring));
  }
  if (uri === '/') {
    request.uri = '/index.html';
    return request;
  }
  if (isSpa(uri)) {
    request.uri = SPA_SHELL;
    return request;
  }
  if (uri === '/index.html') return redirect('/' + queryString(request.querystring));
  if (uri.length > 11 && uri.slice(-11) === '/index.html') {
    return redirect(uri.slice(0, -11) + queryString(request.querystring));
  }
  if (uri.charAt(uri.length - 1) === '/') {
    return redirect((uri.replace(/\\/+$/, '') || '/') + queryString(request.querystring));
  }
  var last = uri.substring(uri.lastIndexOf('/') + 1);
  if (last.indexOf('.') === -1) request.uri = uri + '/index.html';
  return request;
}
`;
}

if (process.argv.includes('--write')) {
  writeFileSync(ROUTER_PATH, buildRouterSource(), 'utf8');
  console.log(`wrote ${ROUTER_PATH}`);
}
